#!/bin/bash
# Ступень C калибровки-2: ПОДТВЕРЖДЕНИЕ кандидатов на восьми мирах.
# Скрининг (4 реплики) умеет только ранжировать точки; число в подписи режима
# обязано стоять на восьми мирах — правило записано в CLAUDE.md после истории,
# когда половина подписей пресетов не воспроизвелась.
# Плюс два парных опыта «свободные гены вкл/выкл на одних сидах» в бедных мирах:
# скрининг показал рост вымирания (24% -> 29%, при свете 0.45 40% -> 68%), и это
# либо цена содержания генов, либо разные сиды. Парный опыт различает.
OUT="${1:?куда писать}"
: > "$OUT"
REP="${REP:-8}"
# Перенаправление ВНУТРИ функции. Дописать `>> "$OUT"` в конец строки вызова
# нельзя: если на строке есть комментарий, редирект попадает внутрь него и молча
# уходит в stdout — ровно та граблина, что записана в README про комментарий,
# проглатывающий продолжение строки. Поймано на этом же файле.
pt() {  # свет мутация разложение паразиты
  for r in $(seq 1 $REP); do
    echo "MODS=1 LIGHT=$1 MUT=$2 DECOMP=$3 PAR=$4 DAYNIGHT=${5:-1} PRED=${6:-1} SEX=${7:-1} SD=$((8000+r)) HOURS=12000" >> "$OUT"
  done
}
# устойчивые миры
pt 0.62 0.12 0.30 1.0     # штатная точка — опора для сравнения >> "$OUT"
pt 0.80 0.12 0.30 1.0     # самый населённый с полной цепью >> "$OUT"
pt 1.00 0.04 0.30 2.0     # населённый при пустом геноме >> "$OUT"
pt 1.00 0.30 0.30 2.0     # населённый при богатом геноме >> "$OUT"
# показательные механики
pt 0.80 0.60 0.60 1.0     # многоклеточность >> "$OUT"
pt 0.62 0.30 0.60 2.0     # половой мир >> "$OUT"
pt 0.80 0.04 0.30 1.0     # Красная Королева >> "$OUT"
pt 1.00 0.30 0.60 2.0     # грибоядные >> "$OUT"
pt 0.80 0.60 0.05 2.0     # банк покоя >> "$OUT"
pt 1.00 0.60 0.30 2.0     # двудомность >> "$OUT"
pt 0.80 0.12 0.60 2.0     # много родов — с исправленным полным графом >> "$OUT"
# парный опыт: цена свободных генов в бедном мире
for L in 0.45; do for M in 0.12 0.30; do for MD in 0 1; do
  for r in $(seq 1 $REP); do
    echo "MODS=$MD LIGHT=$L MUT=$M DECOMP=0.30 PAR=1.0 DAYNIGHT=1 PRED=1 SEX=1 SD=$((8000+r)) HOURS=12000"
  done
done; done; done >> "$OUT"
wc -l < "$OUT"
